| BFS — CRC32 in 68020+ assembly
|
| uint32_t bfs_crc32(uint32_t initial, const void *data, size_t len)
|
| IEEE 802.3 reflected polynomial (0xEDB88320).
| Uses slicing by four with native big-endian internal CRC state/tables.
| External seed/chaining/results retain the reflected IEEE CRC convention.

        .text
        .even
        .globl  _bfs_crc32

| Arguments (C calling convention, stack-based):
|   4(sp) = initial (uint32_t)
|   8(sp) = data    (const void *)
|  12(sp) = len     (size_t / uint32_t)

_bfs_crc32:
        movem.l d2-d4/a2-a4,-(sp)       | save callee-saved registers
        | Adjust stack offsets: +24 for saved regs
        move.l  28(sp),d0               | d0 = initial
        move.l  32(sp),a0               | a0 = data pointer
        move.l  36(sp),d2               | d2 = len

        not.l   d0                      | R = byte_swap(~initial)
        rol.w   #8,d0
        swap    d0
        rol.w   #8,d0
        lea     crc32_table_68k(pc),a1  | a1 = T0
        lea     0x400(a1),a2            | a2 = T1
        lea     0x800(a1),a3            | a3 = T2
        lea     0xC00(a1),a4            | a4 = T3

        | Handle zero length before reading data.
        tst.l   d2
        beq     .Ldone

        | Process complete 4-byte blocks; d2 remains the byte count.
        cmpi.l  #4,d2
        bcs.s   .Ltail

.Lloop4:
        | D = R ^ native_big_endian_word. Tables contain byte-swapped
        | reflected results: R' = T0[D&255] ^ T1[(D>>8)&255]
        |                        ^ T2[(D>>16)&255] ^ T3[D>>24].
        | Existing 68020+ unaligned word-load behavior is unchanged.
        move.l  (a0)+,d1
        eor.l   d0,d1

        moveq   #0,d3
        move.b  d1,d3
        move.l  (a1,d3.w*4),d4

        move.w  d1,d3
        lsr.w   #8,d3
        move.l  (a2,d3.w*4),d3
        eor.l   d3,d4

        move.l  d1,d3
        swap    d3
        andi.w  #0x00FF,d3
        move.l  (a3,d3.w*4),d3
        eor.l   d3,d4

        move.l  d1,d3
        swap    d3
        lsr.w   #8,d3
        move.l  (a4,d3.w*4),d3
        eor.l   d3,d4

        move.l  d4,d0
        subq.l  #4,d2
        cmpi.l  #4,d2
        bcc.s   .Lloop4

.Ltail:
        | Process remaining 0-3 bytes with the base table.
        tst.l   d2
        beq.s   .Ldone

.Lloop1:
        | R' = byte_swap(T0[(R>>24)^byte]) ^ (R<<8).
        move.l  d0,d1
        rol.l   #8,d1
        move.b  (a0)+,d3
        eor.b   d3,d1
        andi.w  #0x00FF,d1
        lsl.l   #8,d0
        move.l  (a1,d1.w*4),d4
        eor.l   d4,d0

        subq.l  #1,d2
        bne.s   .Lloop1

.Ldone:
        rol.w   #8,d0
        swap    d0
        rol.w   #8,d0
        not.l   d0                      | return ~crc
        movem.l (sp)+,d2-d4/a2-a4       | restore registers
        rts

